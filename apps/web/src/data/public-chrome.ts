type ChromeMap = typeof publicChrome;

export function pickChrome<K extends keyof ChromeMap>(
  key: K,
  locale: Locale,
): ChromeMap[K][Locale] {
  const row = publicChrome[key];
  return (row[locale] ?? row.en) as ChromeMap[K][Locale];
}
